/// Attaches DWARF debug metadata to the module that an LLVMCodeGenerator is building,
/// so that a debugger can step through JIT-compiled code and inspect its variables.
///
/// The type mappings here must mirror LLVMCodeGenerator::getLLVMType(), and the sizes
/// and offsets are taken from the generator's layout so that they can't disagree
/// with the code that gets generated.
template <typename CodeGeneratorType>
struct DebugInfoGenerator
{
    DebugInfoGenerator (CodeGeneratorType& generator, ::llvm::Module& module, bool willBeOptimised)
        : owner (generator), context (module.getContext()), builder (module), isOptimised (willBeOptimised)
    {
        module.addModuleFlag (::llvm::Module::Warning, "Debug Info Version", ::llvm::DEBUG_METADATA_VERSION);
        module.addModuleFlag (::llvm::Module::Warning, "Dwarf Version", 4);

        unknownFile = builder.createFile ("<cmajor>", {});

        compileUnit = builder.createCompileUnit (::llvm::dwarf::DW_LANG_C_plus_plus, findMainFile(), "Cmajor", isOptimised, {}, 0);

        subroutineType = builder.createSubroutineType (builder.getOrCreateTypeArray ({}));
    }

    void finalise()
    {
        builder.finalize();
    }

    //==============================================================================
    void beginFunction (const AST::Function& fn, ::llvm::Function& function)
    {
        auto position = findPosition (fn.context.location);

        // Code without a source position is either compiler-generated, or comes from a
        // pre-compiled module such as the standard library. It still needs a subprogram
        // so that it has a readable name in a backtrace, because its symbols are private.
        auto file = position.file != nullptr ? position.file : unknownFile;
        auto flags = position.file != nullptr ? ::llvm::DINode::FlagPrototyped : ::llvm::DINode::FlagArtificial;

        subprogram = builder.createFunction (file, fn.getFullyQualifiedReadableName(), function.getName(), file,
                                             position.line, subroutineType, position.line, flags,
                                             isOptimised ? ::llvm::DISubprogram::SPFlagDefinition | ::llvm::DISubprogram::SPFlagOptimized
                                                         : ::llvm::DISubprogram::SPFlagDefinition);
        function.setSubprogram (subprogram);

        lexicalBlocks.clear();
        lexicalBlockFiles.clear();
        currentLocation = ::llvm::DILocation::get (context, position.line, position.column, subprogram);
    }

    /// Moves the current location to this statement. Anything without a position of its
    /// own was generated by the compiler, and is left attributed to the previous statement.
    void setStatementLocation (const AST::Object& statement)
    {
        auto position = findPosition (statement.context.location);

        if (position.file != nullptr)
            currentLocation = createLocation (position, getScope (statement));
    }

    ::llvm::DebugLoc getCurrentLocation() const     { return currentLocation; }

    //==============================================================================
    /// Describes a local variable. Temporaries that the compiler has created have no
    /// source position, and are skipped so that they don't clutter up the debugger.
    void declareLocalVariable (const AST::VariableDeclaration& v, ::llvm::Value* storage, ::llvm::BasicBlock& block)
    {
        auto position = findPosition (v.context.location);

        if (position.file == nullptr)
            return;

        auto scope = getScope (v);
        auto variable = builder.createAutoVariable (scope, std::string (v.getName()), position.file,
                                                    position.line, getType (*v.getType()), true);

        builder.insertDeclare (storage, variable, builder.createExpression(),
                               createLocation (position, scope), std::addressof (block));
    }

    /// Describes a parameter that lives in the given stack slot. If storageHoldsPointerToValue
    /// is true, then the slot holds a pointer to a parameter which was passed by value.
    void declareParameter (const AST::VariableDeclaration& param, const AST::TypeBase& type, unsigned argumentNumber,
                           ::llvm::Value* storage, bool storageHoldsPointerToValue, ::llvm::BasicBlock& block)
    {
        auto position = findPosition (param.context.location);

        if (position.file == nullptr)
            position = { subprogram->getFile(), subprogram->getLine(), 0 };

        auto variable = builder.createParameterVariable (subprogram, std::string (param.getName()), argumentNumber,
                                                         position.file, position.line, getType (type), true);

        auto expression = storageHoldsPointerToValue ? builder.createExpression (::llvm::ArrayRef<uint64_t> { ::llvm::dwarf::DW_OP_deref })
                                                     : builder.createExpression();

        builder.insertDeclare (storage, variable, expression, createLocation (position, subprogram), std::addressof (block));
    }

    void declareGlobalVariable (const AST::VariableDeclaration& v, const AST::TypeBase& type, ::llvm::GlobalVariable& global)
    {
        auto position = findPosition (v.context.location);

        global.addDebugInfo (builder.createGlobalVariableExpression (compileUnit, std::string (v.getName()), global.getName(),
                                                                     position.file != nullptr ? position.file : unknownFile,
                                                                     position.line, getType (type), true));
    }

private:
    //==============================================================================
    struct SourcePosition
    {
        ::llvm::DIFile* file = nullptr;
        unsigned line = 0, column = 0;
    };

    struct SourceFileInfo
    {
        ::llvm::DIFile* file = nullptr;
        std::vector<const char*> lineStarts;
    };

    CodeGeneratorType& owner;
    ::llvm::LLVMContext& context;
    ::llvm::DIBuilder builder;
    const bool isOptimised;

    ::llvm::DICompileUnit* compileUnit = nullptr;
    ::llvm::DIFile* unknownFile = nullptr;
    ::llvm::DISubroutineType* subroutineType = nullptr;
    ::llvm::DISubprogram* subprogram = nullptr;
    ::llvm::DILocation* currentLocation = nullptr;

    std::unordered_map<const SourceFile*, SourceFileInfo> sourceFiles;
    std::unordered_map<const AST::ScopeBlock*, ::llvm::DIScope*> lexicalBlocks;
    std::map<std::pair<::llvm::DIScope*, ::llvm::DIFile*>, ::llvm::DIScope*> lexicalBlockFiles;
    std::unordered_map<const AST::Object*, ::llvm::DIType*> compositeTypes;

    //==============================================================================
    ::llvm::DIFile* findMainFile()
    {
        for (auto& f : owner.allocator.sourceFileList.sourceFiles)
            if (! f->isSystem)
                return getSourceFileInfo (*f).file;

        return unknownFile;
    }

    ::llvm::DIFile* createFile (const std::string& filename)
    {
        if (filename.empty())
            return unknownFile;

        // A debugger needs an absolute path to find the source, but a patch's
        // files are named relative to wherever it was loaded from
        std::error_code error;
        auto path = std::filesystem::absolute (filename, error);

        if (error)
            return builder.createFile (filename, {});

        return builder.createFile (path.filename().string(), path.parent_path().string());
    }

    SourceFileInfo& getSourceFileInfo (const SourceFile& sourceFile)
    {
        auto found = sourceFiles.find (std::addressof (sourceFile));

        if (found != sourceFiles.end())
            return found->second;

        auto& info = sourceFiles[std::addressof (sourceFile)];
        info.file = createFile (sourceFile.filename);

        auto text = sourceFile.content.data();
        auto end = text + sourceFile.content.length();

        info.lineStarts.push_back (text);

        for (auto c = text; c != end; ++c)
            if (*c == '\n')
                info.lineStarts.push_back (c + 1);

        return info;
    }

    SourcePosition findPosition (CodeLocation location)
    {
        if (location.empty())
            return {};

        auto sourceFile = owner.allocator.sourceFileList.findSourceFileContaining (location);

        if (sourceFile == nullptr)
            return {};

        auto& info = getSourceFileInfo (*sourceFile);
        auto text = location.text.data();
        auto nextLine = std::upper_bound (info.lineStarts.begin(), info.lineStarts.end(), text);
        auto line = static_cast<unsigned> (nextLine - info.lineStarts.begin());

        return { info.file, line, static_cast<unsigned> (text - *(nextLine - 1)) + 1 };
    }

    //==============================================================================
    ::llvm::DIScope* getScope (const AST::Object& object)
    {
        for (auto o = std::addressof (object); o != nullptr; o = o->getParentScope().get())
        {
            if (o->getAsFunction() != nullptr)
                break;

            if (auto block = o->getAsScopeBlock())
                return getLexicalBlock (*block);
        }

        return subprogram;
    }

    ::llvm::DIScope* getLexicalBlock (const AST::ScopeBlock& block)
    {
        auto found = lexicalBlocks.find (std::addressof (block));

        if (found != lexicalBlocks.end())
            return found->second;

        auto parent = block.getParentScope();
        auto parentScope = parent != nullptr ? getScope (*parent) : subprogram;
        auto position = findPosition (block.context.location);
        auto isFunctionBody = parent != nullptr && parent->getAsFunction() != nullptr;

        auto scope = (position.file == nullptr || isFunctionBody)
                        ? parentScope
                        : builder.createLexicalBlock (parentScope, position.file, position.line, position.column);

        lexicalBlocks[std::addressof (block)] = scope;
        return scope;
    }

    /// A location takes its filename from its scope, so anything that has been inlined
    /// from another file needs wrapping in a scope that specifies the right file.
    ::llvm::DILocation* createLocation (const SourcePosition& position, ::llvm::DIScope* scope)
    {
        if (scope->getFile() != position.file)
        {
            auto& fileScope = lexicalBlockFiles[{ scope, position.file }];

            if (fileScope == nullptr)
                fileScope = builder.createLexicalBlockFile (scope, position.file);

            scope = fileScope;
        }

        return ::llvm::DILocation::get (context, position.line, position.column, scope);
    }

    //==============================================================================
    uint64_t getSizeInBits (const AST::TypeBase& type)      { return static_cast<uint64_t> (owner.getPaddedTypeSize (type)) * 8; }
    uint32_t getAlignInBits (const AST::TypeBase& type)     { return static_cast<uint32_t> (owner.getTypeAlignment (type)) * 8; }
    uint64_t getPointerSizeInBits()                         { return owner.getDataLayout().getPointerSizeInBits(); }

    ::llvm::DIType* createBasicType (std::string_view name, uint64_t sizeInBits, unsigned encoding)
    {
        return builder.createBasicType (std::string (name), sizeInBits, encoding);
    }

    ::llvm::DINodeArray createSubscripts (int64_t numElements)
    {
        return builder.getOrCreateArray ({ builder.getOrCreateSubrange (0, numElements) });
    }

    ::llvm::DIType* getType (const AST::TypeBase& type)
    {
        if (auto mcr = type.getAsMakeConstOrRef())
        {
            auto sourceType = getType (*mcr->getSource());

            if (mcr->makeRef)
                return builder.createReferenceType (::llvm::dwarf::DW_TAG_reference_type, sourceType, getPointerSizeInBits());

            return sourceType;
        }

        if (type.isVoid())              return nullptr;
        if (type.isPrimitiveInt32())    return createBasicType ("int32",   32, ::llvm::dwarf::DW_ATE_signed);
        if (type.isPrimitiveInt64())    return createBasicType ("int64",   64, ::llvm::dwarf::DW_ATE_signed);
        if (type.isPrimitiveFloat32())  return createBasicType ("float32", 32, ::llvm::dwarf::DW_ATE_float);
        if (type.isPrimitiveFloat64())  return createBasicType ("float64", 64, ::llvm::dwarf::DW_ATE_float);
        if (type.isPrimitiveBool())     return createBasicType ("bool",    8,  ::llvm::dwarf::DW_ATE_boolean);

        // At runtime a string is just a handle to an entry in the string dictionary
        if (type.isPrimitiveString())   return createBasicType ("string",  32, ::llvm::dwarf::DW_ATE_unsigned);

        if (auto e = type.getAsEnumType())
            return getEnumType (*e);

        if (auto v = type.getAsVectorType())
            return getVectorType (*v);

        if (auto a = type.getAsArrayType())
        {
            if (a->isSlice())
                return getSliceType (*type.getArrayOrVectorElementType());

            return builder.createArrayType (getSizeInBits (type), getAlignInBits (type),
                                            getType (a->getInnermostElementTypeRef()),
                                            createSubscripts (static_cast<int64_t> (a->resolveSize())));
        }

        if (auto s = type.getAsStructType())
            return getStructType (*s);

        CMAJ_ASSERT_FALSE;
        return {};
    }

    ::llvm::DIType* getVectorType (const AST::VectorType& v)
    {
        auto& elementType = v.getElementType();
        auto numElements = static_cast<int64_t> (v.resolveSize());

        if (numElements == 1)
            return getType (elementType);

        // LLVM packs a vector of bools into single bits, which DWARF has no way to describe
        if (elementType.isPrimitiveBool())
            return createBasicType ("bool<" + std::to_string (numElements) + ">", getSizeInBits (v), ::llvm::dwarf::DW_ATE_unsigned);

        return builder.createVectorType (getSizeInBits (v), getAlignInBits (v), getType (elementType), createSubscripts (numElements));
    }

    ::llvm::DIType* getEnumType (const AST::EnumType& e)
    {
        auto found = compositeTypes.find (std::addressof (e));

        if (found != compositeTypes.end())
            return found->second;

        ::llvm::SmallVector<::llvm::Metadata*, 16> enumerators;
        uint64_t value = 0;

        for (auto& item : e.items)
            if (auto name = item->getAsStringProperty())
                enumerators.push_back (builder.createEnumerator (std::string (name->get()), value++));

        auto position = findPosition (e.context.location);
        auto file = position.file != nullptr ? position.file : unknownFile;

        auto type = builder.createEnumerationType (file, std::string (e.getName()), file, position.line, 32, 32,
                                                   builder.getOrCreateArray (enumerators),
                                                   createBasicType ("int32", 32, ::llvm::dwarf::DW_ATE_signed));

        compositeTypes[std::addressof (e)] = type;
        return type;
    }

    ::llvm::DIType* getSliceType (const AST::TypeBase& elementType)
    {
        auto layout = owner.getDataLayout().getStructLayout (owner.getFatPointerType (elementType));
        auto pointerSize = getPointerSizeInBits();

        auto dataMember = builder.createMemberType (unknownFile, "data", unknownFile, 0, pointerSize, 0, 0, ::llvm::DINode::FlagZero,
                                                    builder.createPointerType (getType (elementType), pointerSize));

        auto sizeMember = builder.createMemberType (unknownFile, "size", unknownFile, 0, 32, 0,
                                                    layout->getElementOffsetInBits (1), ::llvm::DINode::FlagZero,
                                                    createBasicType ("int32", 32, ::llvm::dwarf::DW_ATE_signed));

        return builder.createStructType (unknownFile, "slice", unknownFile, 0, layout->getSizeInBits(), 0, ::llvm::DINode::FlagZero, nullptr,
                                         builder.getOrCreateArray ({ dataMember, sizeMember }));
    }

    ::llvm::DIType* getStructType (const AST::StructType& s)
    {
        auto found = compositeTypes.find (std::addressof (s));

        if (found != compositeTypes.end())
            return found->second;

        auto position = findPosition (s.context.location);
        auto file = position.file != nullptr ? position.file : unknownFile;
        auto name = std::string (s.getName());

        // A struct can refer back to itself via a slice, so this forward declaration
        // has to be visible while its members are being created
        auto declaration = builder.createReplaceableCompositeType (::llvm::dwarf::DW_TAG_structure_type, name, file, file, position.line);
        compositeTypes[std::addressof (s)] = declaration;

        ::llvm::SmallVector<::llvm::Metadata*, 32> members;

        for (size_t i = 0; i < s.memberTypes.size(); ++i)
        {
            auto& memberType = s.getMemberType (i);
            auto offset = static_cast<uint64_t> (owner.getStructMemberOffset (s, static_cast<uint32_t> (i))) * 8;

            members.push_back (builder.createMemberType (declaration, std::string (s.getMemberName (i)), file, position.line,
                                                         getSizeInBits (memberType), getAlignInBits (memberType), offset,
                                                         ::llvm::DINode::FlagZero, getType (memberType)));
        }

        auto definition = builder.createStructType (file, name, file, position.line, getSizeInBits (s), getAlignInBits (s),
                                                    ::llvm::DINode::FlagZero, nullptr, builder.getOrCreateArray (members));

        builder.replaceTemporary (::llvm::TempMDNode (declaration), definition);
        compositeTypes[std::addressof (s)] = definition;
        return definition;
    }
};

